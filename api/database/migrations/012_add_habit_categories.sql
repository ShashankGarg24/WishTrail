ALTER TABLE habits
  ADD COLUMN IF NOT EXISTS category VARCHAR(32) NOT NULL DEFAULT 'OTHER';

UPDATE habits SET category = 'OTHER'
WHERE category IS NULL OR category NOT IN (
  'FITNESS', 'NUTRITION', 'MINDFULNESS', 'LEARNING', 'PRODUCTIVITY', 'CAREER',
  'FINANCE', 'CREATIVITY', 'SELF_CARE', 'SOCIAL', 'HOME', 'OTHER'
);

ALTER TABLE habits DROP CONSTRAINT IF EXISTS habits_category_check;
ALTER TABLE habits ADD CONSTRAINT habits_category_check CHECK (category IN (
  'FITNESS', 'NUTRITION', 'MINDFULNESS', 'LEARNING', 'PRODUCTIVITY', 'CAREER',
  'FINANCE', 'CREATIVITY', 'SELF_CARE', 'SOCIAL', 'HOME', 'OTHER'
));

CREATE INDEX IF NOT EXISTS idx_habits_category ON habits(category);
